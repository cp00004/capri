const port = process.argv[2] || "9225";
const list = await (await fetch(`http://127.0.0.1:${port}/json`)).json();
const page = list.find((t) => t.type === "page");
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.onmessage = (ev) => { const m = JSON.parse(ev.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } };
const send = (method, params = {}) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
await new Promise((r) => { ws.onopen = r; });
const shot = await send("Page.captureScreenshot", { format: "png" });
const fs = await import("node:fs");
fs.writeFileSync("tmp-page.png", Buffer.from(shot.result.data, "base64"));
const info = await send("Runtime.evaluate", { expression: "JSON.stringify({url: location.href, text: (document.body.innerText||'').slice(0,120), imgs: [...document.images].map(i=>[i.getAttribute('src'), i.naturalWidth])})", returnByValue: true });
console.log(info.result?.result?.value);
process.exit(0);
